// Funcion utilitaria para normalizar texto (quitar tildes y minusculas)
export const normalizarTexto = (texto) => {
  if (!texto) return "";
  return texto
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();
};

// Buscador predictivo rapido
export const buscarComunasChile = (termino, limite = 7) => {
  if (!termino || termino.trim().length === 0) return [];
  
  const query = normalizarTexto(termino);
  
  return COMUNAS_CHILE
    .filter((item) => {
      const nombreComuna = normalizarTexto(item.comuna);
      const nombreRegion = normalizarTexto(item.region);
      return nombreComuna.includes(query) || nombreRegion.includes(query);
    })
    .slice(0, limite);
};

